#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int	i;
	int	sign;
	long	resultat;

	i = 0;
	sign = 1;
	resultat = 0;
	while (nptr[i] == ' ' || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-')
	{
		sign = -1;
		i++;
	}
	else if (nptr[i] == '+')
		i++;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		resultat = resultat * 10 + (nptr[i] - '0');
		i++;
	}
	return (sign * resultat);
}
